/**
 * The one seam between the Build screens and the store that holds a universe's map
 * (findings/builder_system_design.md; directives/prompts/builder_step1.md). The screens call
 * only what is declared here. Agent A's `apps/web/src/builder/` takes the stand-in's place by
 * one call to `useBuildStore`; `stand_in.ts` is then deleted.
 *
 * Nothing here reads an engine's tree: a tree is handed to the dossier whole.
 */
import type { SectorHex, TreeEnvelope } from '@voyage/shared';
import { shallowRef } from 'vue';

/** What a hex is on this map. `truth` and `empty` have no row of the builder's. */
export type HexState = 'empty' | 'truth' | 'override' | 'own' | 'removed';

export type Generator = 'bottom-up' | 'top-down';
export type GenerateChoice = { engine: string; generator: Generator };

/** A row of the builder's: a system of theirs, or a chart system they removed. */
export type BuildRow = {
    hexKey: string;
    state: 'override' | 'own' | 'removed';
    /** The chart row the map draws; null for a removed hex. */
    entry: SectorHex | null;
    roll: number;
    rev: number;
};

/** A system rolled and not kept. */
export type Preview = {
    hexKey: string;
    choice: GenerateChoice;
    roll: number;
    entry: SectorHex;
    tree: TreeEnvelope;
};

export type JobState = 'running' | 'stopping' | 'stopped' | 'done';
export type JobProgress = { total: number; done: number; failed: string[]; state: JobState };

/** What one Undo puts back. Opaque to the screens. */
export type UndoToken = { id: string };

/**
 * An Undo that did not put everything back (findings/builder_undo_faults.md). `left` is the hex
 * keys still as they were; `message` is the server's sentence when it refused, or empty when a
 * job left the hexes that had changed.
 */
export type UndoOutcome = { id: string; restored: number; left: string[]; message: string };

export type BuildUniverse = { id: string; name: string; truthVersion: string | null };

export type BuildStore = {
    /** The universe being built, or null when none is open. */
    universe(): BuildUniverse | null;
    /** A number that changes whenever any row does; reactive. */
    tick(): number;
    row(hexKey: string): BuildRow | null;
    /** Every row in one sector, for laying over that sector's chart index. */
    rows(slug: string): BuildRow[];
    tree(hexKey: string): Promise<TreeEnvelope | null>;
    /** Rolls a system and stores nothing. `truth` is the chart row under the hex, if any. */
    preview(hexKey: string, choice: GenerateChoice, roll: number, truth: SectorHex | null): Promise<Preview>;
    keep(preview: Preview, truth: SectorHex | null): Promise<UndoToken>;
    /** Many hexes. `onProgress` is called as each lands. `stop` leaves what is done. */
    generateMany(
        hexes: { hexKey: string; truth: SectorHex | null }[],
        choice: GenerateChoice,
        onProgress: (progress: JobProgress) => void,
    ): { stop: () => void; finished: Promise<{ token: UndoToken; progress: JobProgress }> };
    /** A chart system is hidden (`removed`); a system with no chart under it is gone. */
    remove(hexes: { hexKey: string; truth: SectorHex | null }[]): Promise<UndoToken>;
    /** The builder's row is dropped: the chart shows again. */
    restore(hexKeys: string[]): Promise<UndoToken>;
    /**
     * Many hexes, some in empty slots, as one act: the slots' sectors are made and the systems
     * generated by one request (findings/builder_grow_ready.md). A slot's hex is `~slot_<x>_<y>/<hhhh>`.
     */
    generateGrowing(body: GrowBody, onProgress?: (progress: GrowProgress) => void): GrowHandle;
    /** Takes the act back. An act that can be put back again answers with the token that does it. */
    undo(token: UndoToken): Promise<UndoToken | UndoOutcome | null | void>;
};

export type GrowBody = {
    hexKeys: readonly string[];
    edition: string;
    generator: Generator;
    roll: number;
    filledToo: boolean;
    makeSectors: readonly { name: string; slot: Slot }[];
};

/** The store's own count of the act, as it polls: its states, not the screen's. */
export type GrowProgress = { total: number; done: number; failed: string[]; state: string };

export type GrowHandle = {
    stop(): void;
    /** At the server's answer: the sectors made, each slot key's real key, and the one Undo, good while the job runs. */
    accepted: Promise<{ sectors: OwnSector[]; keys: Record<string, string>; undo: UndoToken }>;
    /** When the job ends; at the answer for one hex. */
    finished: Promise<{ undo: UndoToken; progress: GrowProgress }>;
};

// ---- step 3: the referee's own sectors, and a system designed by hand ------------------------------

/** A place on the grid of sectors. */
export type Slot = { x: number; y: number };

/** A sector the referee made (packages/shared `RefereeSector`), as the screens read it. */
export type OwnSector = { id: string; slot: Slot; name: string; subsectors: string[]; rev: number };

/**
 * What one Undo of a sector act puts back. Opaque to the screens. `toRev` is the revision
 * whose stored copy returns; `atRev` is the revision the act made, and the Undo applies only
 * while the sector still stands there.
 */
export type SectorUndoToken = { id: string; toRev: number; atRev: number };

/**
 * The referee's sectors of the open universe, and the two calls a hand-designed system needs
 * beside its draft. Answered by Agent A's store (`builder/sectors.ts`, `Builder.sectors()`).
 */
export type OwnSectors = {
    /** A number that changes whenever a sector does; reactive. */
    tick(): number;
    /** False until the first list has arrived. */
    loaded(): boolean;
    list(): OwnSector[];
    get(id: string): OwnSector | null;
    make(name: string, slot: Slot): Promise<OwnSector>;
    rename(id: string, name: string): Promise<SectorUndoToken>;
    move(id: string, slot: Slot): Promise<SectorUndoToken>;
    /** The sector and its hexes go; the server keeps a copy first. */
    remove(id: string): Promise<SectorUndoToken>;
    /** An empty name clears it. */
    renameSubsector(id: string, letter: string, name: string): Promise<SectorUndoToken>;
    undo(token: SectorUndoToken): Promise<void>;
    /** Whether the stored system is designed by hand; null when the hex holds none. */
    formMode(hexKey: string): Promise<'hand' | 'generated' | null>;
    /** The stored system (or the chart's, at rev 0) becomes a hand-designed one. The returned call puts the earlier version back. */
    designByHand(hexKey: string, baseRev: number): Promise<() => Promise<void>>;
};

/**
 * Held in a ref: the store is opened after the screens are (when the universe is known), and a
 * screen that asked for it while it was null must hear when it arrives.
 */
const current = shallowRef<BuildStore | null>(null);
const sectors = shallowRef<OwnSectors | null>(null);

export function useOwnSectors(store: OwnSectors | null): void {
    sectors.value = store;
}

export function ownSectors(): OwnSectors | null {
    return sectors.value;
}

export function useBuildStore(store: BuildStore | null): void {
    current.value = store;
}

export function buildStore(): BuildStore | null {
    return current.value;
}
