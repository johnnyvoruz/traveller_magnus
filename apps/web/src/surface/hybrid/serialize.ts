/**
 * Saved hex data for the hybrid map (design §10): the generated hexes in a compact,
 * versioned form, and a referee's edits on top of them.
 *
 * Edits are kept apart from the generated data. A saved map is regenerated from the world
 * (the generator is deterministic) and the edits are laid over it; the generated payload is
 * a record for checking and export, not the source of truth.
 *
 * Storage: there is no server endpoint for surface edits yet (UniverseDO has none). HexEditStore
 * is the client-side interface; memoryEditStore is the one implementation. A server-backed store
 * implements the same three calls.
 */
import { isSurfaceCode, TERRAIN_CODES, type SurfaceCode, type TerrainCode } from './codes.ts';
import { HYBRID_SURFACE_VERSION } from './inputs.ts';
import type { HexRecord, HybridModel } from './model.ts';

export const HEX_DATA_FORMAT = 1;

/** One hex, compact. Field order is fixed: see HEX_FIELDS. */
export type PackedHex = [
    id: number, row: number, col: number, terrain: string, water: 0 | 1, ice: string, elevation: number,
    tempK: number, moisture: number, accents: string, features: string, port: string, domed: 0 | 1,
];

export const HEX_FIELDS = ['id', 'row', 'col', 'terrain', 'water', 'ice', 'elevation', 'tempK', 'moisture', 'accents', 'features', 'port', 'domed'] as const;

export type HexData = {
    readonly format: typeof HEX_DATA_FORMAT;
    /** Generator version; a different one means the hexes were generated by other rules. */
    readonly surface: string;
    readonly seed: string;
    readonly n: number;
    readonly hexes: readonly PackedHex[];
};

const round = (v: number, places: number): number => Number(v.toFixed(places));

export function packHexes(model: HybridModel): HexData {
    return {
        format: HEX_DATA_FORMAT,
        surface: HYBRID_SURFACE_VERSION,
        seed: model.world.seed,
        n: model.grid.n,
        hexes: model.hexes.map((h) => [
            h.id, h.row, h.col, h.terrain, h.water ? 1 : 0, h.ice, round(h.elevation, 3), round(h.tempK, 1), round(h.moisture, 3),
            h.accents.join(' '), h.features.join(' '), h.port ?? '', h.domed ? 1 : 0,
        ] as PackedHex),
    };
}

export type UnpackedHex = Pick<HexRecord, 'id' | 'row' | 'col' | 'terrain' | 'water' | 'ice' | 'elevation' | 'tempK' | 'moisture' | 'accents' | 'features' | 'port' | 'domed'>;

/** Read packed hex data. Throws on a format this code does not know. */
export function unpackHexes(data: unknown): { surface: string; seed: string; n: number; hexes: UnpackedHex[] } {
    const d = data as HexData;
    if (!d || typeof d !== 'object' || d.format !== HEX_DATA_FORMAT || !Array.isArray(d.hexes)) {
        throw new Error('hex data: unknown format ' + String(d && (d as { format?: unknown }).format));
    }
    return {
        surface: d.surface,
        seed: d.seed,
        n: d.n,
        hexes: d.hexes.map((p) => ({
            id: p[0], row: p[1], col: p[2], terrain: p[3] as TerrainCode, water: p[4] === 1, ice: p[5] as HexRecord['ice'],
            elevation: p[6], tempK: p[7], moisture: p[8],
            accents: (p[9] ? p[9].split(' ') : []) as HexRecord['accents'],
            features: (p[10] ? p[10].split(' ') : []) as HexRecord['features'],
            port: p[11] || null, domed: p[12] === 1,
        })),
    };
}

/** A referee's change to one hex, addressed by row and column so it survives regeneration. */
export type HexEdit = {
    readonly row: number;
    readonly col: number;
    readonly terrain?: TerrainCode;
    /** Replaces the hex's features when present. */
    readonly features?: readonly SurfaceCode[];
    readonly accents?: readonly SurfaceCode[];
    readonly note?: string;
};

export const HEX_EDITS_FORMAT = 1;

export type HexEdits = {
    readonly format: typeof HEX_EDITS_FORMAT;
    /** Grid side the edits were made on; edits for another side are not applied. */
    readonly n: number;
    readonly edits: readonly HexEdit[];
};

export function serializeEdits(n: number, edits: readonly HexEdit[]): string {
    const sorted = [...edits].sort((a, b) => a.row - b.row || a.col - b.col);
    return JSON.stringify({ format: HEX_EDITS_FORMAT, n, edits: sorted } satisfies HexEdits);
}

export function parseEdits(text: string): HexEdits {
    const raw = JSON.parse(text) as HexEdits;
    if (!raw || raw.format !== HEX_EDITS_FORMAT || !Array.isArray(raw.edits) || typeof raw.n !== 'number') {
        throw new Error('hex edits: unknown format');
    }
    const terrains = new Set<string>(TERRAIN_CODES);
    const edits = raw.edits.filter((e) => e && Number.isInteger(e.row) && Number.isInteger(e.col)).map((e) => ({
        row: e.row,
        col: e.col,
        ...(e.terrain && terrains.has(e.terrain) ? { terrain: e.terrain } : {}),
        ...(Array.isArray(e.features) ? { features: e.features.filter((c: unknown): c is SurfaceCode => typeof c === 'string' && isSurfaceCode(c)) } : {}),
        ...(Array.isArray(e.accents) ? { accents: e.accents.filter((c: unknown): c is SurfaceCode => typeof c === 'string' && isSurfaceCode(c)) } : {}),
        ...(typeof e.note === 'string' ? { note: e.note } : {}),
    }));
    return { format: HEX_EDITS_FORMAT, n: raw.n, edits };
}

/** The model's hexes with edits laid over them (a copy; the model is not changed). */
export function applyEdits(model: HybridModel, edits: HexEdits | null): HexRecord[] {
    const hexes = model.hexes.map((h) => ({ ...h, accents: [...h.accents], features: [...h.features] }));
    if (!edits || edits.n !== model.grid.n) return hexes;
    for (const e of edits.edits) {
        if (!(e.row >= 0 && e.row <= 3 * model.grid.n)) continue;
        const start = model.grid.rowStart[e.row];
        const end = model.grid.rowStart[e.row + 1];
        const id = start + e.col;
        if (!(e.col >= 0 && id < end)) continue;
        const h = hexes[id];
        if (e.terrain) {
            h.terrain = e.terrain;
            h.water = e.terrain === 'OC' || e.terrain === 'SH' || e.terrain === 'SI' || e.terrain === 'IF';
        }
        if (e.features) h.features = e.features.filter((c) => c !== 'MT' && c !== 'VO' && c !== 'CR') as HexRecord['features'];
        if (e.accents) h.accents = e.accents.filter((c) => c === 'MT' || c === 'VO' || c === 'CR') as HexRecord['accents'];
    }
    return hexes;
}

/** Where edits are kept. Keys are the body's hex key and dossier key. */
export type HexEditStore = {
    load(hexKey: string, dossierKey: string): Promise<HexEdits | null>;
    save(hexKey: string, dossierKey: string, edits: HexEdits): Promise<void>;
    clear(hexKey: string, dossierKey: string): Promise<void>;
};

/** Edits held in memory for this page. Stands in until the server has a home for them. */
export function memoryEditStore(): HexEditStore {
    const held = new Map<string, string>();
    const key = (hexKey: string, dossierKey: string): string => hexKey.length + ':' + hexKey + '|' + dossierKey;
    return {
        async load(hexKey, dossierKey) {
            const text = held.get(key(hexKey, dossierKey));
            return text ? parseEdits(text) : null;
        },
        async save(hexKey, dossierKey, edits) {
            held.set(key(hexKey, dossierKey), serializeEdits(edits.n, edits.edits));
        },
        async clear(hexKey, dossierKey) {
            held.delete(key(hexKey, dossierKey));
        },
    };
}
